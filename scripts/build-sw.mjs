#!/usr/bin/env node
/*
 * Writes out/sw.js after `next build`: a service worker that precaches every
 * file of the static web release, so the web version keeps working offline
 * after the first visit. The cache name changes with the content, so a new
 * release replaces the old cache.
 */
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(process.argv[2] ?? "out");
const files = [];
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (e.name !== "sw.js") files.push(p);
  }
})(root);

const hash = crypto.createHash("sha256");
const urls = [];
for (const f of files.sort()) {
  hash.update(f).update(fs.readFileSync(f));
  const rel = "/" + path.relative(root, f).split(path.sep).join("/");
  urls.push(rel);
  // Pages are requested as "/play/", not "/play/index.html".
  if (rel.endsWith("/index.html")) urls.push(rel.slice(0, -"index.html".length));
}
const version = hash.digest("hex").slice(0, 12);

const sw = `/* Heroes World offline cache — generated by scripts/build-sw.mjs. */
const CACHE = "heroes-world-${version}";
const URLS = ${JSON.stringify(urls)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(URLS)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith("heroes-world-") && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  const url = new URL(req.url);
  if (req.method !== "GET" || url.origin !== self.location.origin) return;
  if (req.mode === "navigate") {
    // Pages: the network when online (fresh release), the cache when offline.
    event.respondWith(
      fetch(req).catch(() =>
        caches.match(url.pathname.endsWith("/") ? url.pathname : url.pathname + "/", { ignoreSearch: true }).then((r) => r || caches.match("/404.html")),
      ),
    );
    return;
  }
  // Scripts, styles, fonts and route data: the cache first (they are versioned).
  event.respondWith(caches.match(req, { ignoreSearch: true }).then((r) => r || fetch(req)));
});
`;
fs.writeFileSync(path.join(root, "sw.js"), sw);
console.log(`out/sw.js: ${urls.length} URLs, cache heroes-world-${version}`);
