TASHKEEL = re.compile(r"[ؐ-ًؚ-ٰٟۖ-ۭـ]")
PUNCT = re.compile(r"[؟،؛.,!?:;…\"'«»()\-–—]")
CLITIC = re.compile(r"^(?:[وفبلك]|ال|وال|بال|فال|لل)$")


def norm(w):
    w = PUNCT.sub("", TASHKEEL.sub("", w))
    w = re.sub("[آأإٱ]", "ا", w)
    return w.replace("ى", "ي").replace("ة", "ه").strip()


def same(spoken, cue):
    a, b = norm(spoken), norm(cue)
    return a == b or (a.endswith(b) and bool(CLITIC.match(a[: len(a) - len(b)])))


def find(words, phrase, start):
    cue = phrase.split()
    for i in range(start, len(words) - len(cue) + 1):
        if all(same(words[i + k]["word"], c) for k, c in enumerate(cue)):
            return i
    return -1


